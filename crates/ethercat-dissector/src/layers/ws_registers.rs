/// Returns `true` if Wireshark's `dissect_esc_register()` runs for this command code
/// (`APRD`, `BRD`, `FPRD`, `APWR`, `APRW`, `FPWR`, `FPRW`, `BWR`, `BRW`, `ARMW`, `FRMW`).
pub fn ws_register_cmd(cmd: u8) -> bool {
    matches!(cmd, 0x01..=0x09 | 0x0D | 0x0E)
}

/// Returns `true` for read commands (`APRD`, `FPRD`, `BRD`) whose register fields Wireshark hides
/// when the working counter is `0`.
pub fn ws_register_read_cmd(cmd: u8) -> bool {
    matches!(cmd, 0x01 | 0x04 | 0x07)
}

/// Lists every Wireshark register instance `(address, length)` completely covered by a datagram
/// payload `[ado, ado + len)` (exact port of the `dissect_esc_register()` coverage loop,
/// including its 16-bit wrap of `ado + len`).
pub fn ws_covered_registers(cmd: u8, ado: u16, len: usize) -> Vec<(u16, u16)> {
    let mut out = Vec::new();
    if len == 0 || !ws_register_cmd(cmd) {
        return out;
    }
    let end_wide = ado as u32 + len as u32;
    let end_u16 = (ado as u32 + len as u32) as u16 as u32;
    for &(reg, length, repeat) in WS_ESC_REGISTERS {
        if end_wide < reg as u32 {
            break;
        }
        let mut reg_offset = reg as u32;
        for _ in 0..repeat {
            if reg_offset >= ado as u32 && reg_offset + length as u32 <= end_u16 {
                out.push((reg_offset as u16, length));
            }
            reg_offset += length as u32;
        }
    }
    out
}

/// Returns `true` if `key` (optionally prefixed `ecat[i].` instead of `ecat.`) is one of the
/// official Wireshark 4.6 register field abbreviations.
pub fn is_official_register_field(key: &str) -> bool {
    let normalized;
    let k = if let Some(rest) = key.strip_prefix("ecat[") {
        match rest.find("].") {
            Some(pos) => {
                normalized = format!("ecat.{}", &rest[pos + 2..]);
                normalized.as_str()
            }
            None => key,
        }
    } else {
        key
    };
    WS_OFFICIAL_REGISTER_FIELDS.binary_search(&k).is_ok()
}

